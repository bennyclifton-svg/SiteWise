import { test, expect } from "@playwright/test";

test("comparison grouping persists, undoes and separates unit rates", async ({page})=>{
 const headers={Origin:"http://127.0.0.1:4173"};
 const {token}=await(await page.request.post("/__e2e/invite?org=a")).json();
 await page.goto(`/#token=${token}`);
 await page.getByLabel("New project").fill("Comparison alignment");
 await page.getByRole("button",{name:"Create project",exact:true}).click();
 await page.waitForURL(/\/projects\/[0-9a-f-]{36}$/);
 const project=new URL(page.url()).pathname.split("/").pop()!;
 const pkg=await(await page.request.post(`/api/projects/${project}/procurement/rows`,{headers,data:{discipline_id:"consultant.town_planner"}})).json();
 const base=`/api/projects/${project}/procurement/packages/${pkg.id}`;
 let table=await(await page.request.post(`${base}/firms`,{headers,data:{firm:{name:"Split services"}}})).json();
 const sub=table.columns[0].submission.id;
 const rows=table.items.filter((i:{base:boolean})=>i.base);
 for(const r of rows) await page.request.put(`/api/projects/${project}/submissions/${sub}/cells/${encodeURIComponent(r.key)}`,{headers,data:{state:"priced",amount:"100.00"}});
 await page.getByRole("button",{name:"Procurement",exact:true}).click();
 await page.getByRole("row",{name:/^Town Planner/}).getByRole("button",{name:/Review Town Planner/}).click();
 await expect(page.getByText("Arrange comparison",{exact:true})).toHaveCount(0);
 await page.getByRole("button",{name:`Move ${rows[0].label} to options`,exact:true}).click();
 await expect(page.getByRole("button",{name:`Move ${rows[0].label} to base fee`,exact:true})).toBeVisible();
 table=await(await page.request.get(`${base}/prices`)).json();
 expect(table.items.find((i:{key:string})=>i.key===rows[0].key).base).toBe(false);
 await page.getByRole("button",{name:`Move ${rows[0].label} to base fee`,exact:true}).click();
 await expect(page.getByRole("button",{name:`Move ${rows[0].label} to options`,exact:true})).toBeVisible();
 await page.getByRole("button",{name:rows[0].label,exact:true}).click();
 await page.getByLabel("Service description").fill("Assessment and approvals");
 await page.getByRole("button",{name:"Save row",exact:true}).click();
 await expect(page.getByRole("button",{name:"Assessment and approvals",exact:true})).toBeVisible();
 await page.getByRole("button",{name:`Move or combine ${rows[1].label}, Split services`,exact:true}).click();
 const targetRow=page.locator(".prices-table tr").filter({has:page.getByRole("button",{name:"Assessment and approvals",exact:true})});
 await targetRow.getByRole("button",{name:"Combine here",exact:true}).click();
 await page.getByRole("button",{name:"Combine fees",exact:true}).click();
 await expect(page.getByRole("button",{name:"Undo last alignment",exact:true})).toBeVisible();
 table=await(await page.request.get(`${base}/prices`)).json();
 expect(table.columns[0].cells[rows[0].key].amount).toBe("200.00");
 expect(table.columns[0].cells[rows[1].key].state).toBe("included");
 await page.getByRole("button",{name:"Undo last alignment",exact:true}).click();
 await expect(page.getByRole("button",{name:"Undo last alignment",exact:true})).toHaveCount(0);
 await page.getByRole("button",{name:"+ Add row",exact:true}).click();
 await page.getByLabel("Service description").fill("Additional inspection");
 await page.getByLabel("Placement").selectOption("rate");
 await page.getByLabel("Rate unit").selectOption("inspection");
 await page.getByRole("button",{name:"Save row",exact:true}).click();
 await expect(page.locator(".prices-table")).toContainText("Additional inspection");
 await expect(page.getByRole("button",{name:"Move Additional inspection to options",exact:true})).toHaveCount(0);
 await page.getByRole("button",{name:`Move or combine ${rows[1].label}, Split services`,exact:true}).click();
 await page.getByRole("button",{name:"Set aside",exact:true}).click();
 await expect(page.getByRole("button",{name:"Undo last alignment",exact:true})).toBeVisible();
 await page.getByRole("button",{name:"Undo last alignment",exact:true}).click();
 await expect(page.getByRole("button",{name:"Undo last alignment",exact:true})).toHaveCount(0);
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:"../tmp/bca-review/alignment-desktop.png",fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:"../tmp/bca-review/alignment-mobile.png",fullPage:true});
});
