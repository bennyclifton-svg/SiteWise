import { expect, test } from "@playwright/test";

test("builder source totals stay separate from allowances and confirmed comparison amounts", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  const headers = { Origin: "http://127.0.0.1:4173" };
  const { token } = await (await page.request.post("/__e2e/invite?org=a")).json();
  await page.goto(`/#token=${token}`);
  await page.getByLabel("New project").fill("Builder comparison");
  await page.getByRole("button", { name: "Create project", exact: true }).click();
  await page.waitForURL(/\/projects\/[0-9a-f-]{36}$/);
  const project = new URL(page.url()).pathname.split("/").pop()!;
  const response = await page.request.post(`/api/projects/${project}/procurement/rows`, { headers, data: { discipline_id: "trade.main_works" } });
  expect(response.ok()).toBeTruthy();
  const pkg = await response.json();
  const base = `/api/projects/${project}/procurement/packages/${pkg.id}`;
  await page.request.post(`${base}/firms`, { headers, data: { firm: { name: "Example Builder" } } });
  const pdf = await (await page.request.get(`/__e2e/proposal.pdf?firm=Example%20Builder&abn=1&lines=${encodeURIComponent("Construction~10000000")}&extra=${encodeURIComponent("Kitchen allowance~2000000")}`)).body();
  await page.getByRole("button", { name: "Procurement", exact: true }).click();
  await page.getByRole("row", { name: /^Main Works/ }).getByRole("button", { name: /(?:Compare|Review) Main Works/ }).click();
  await page.getByLabel("Options for Example Builder").click();
  await page.getByLabel("Upload proposal for Example Builder").setInputFiles({ name: "Builder.pdf", mimeType: "application/pdf", buffer: pdf });
  const quoted = page.locator(".builder-quoted");
  await expect(quoted).toContainText("$100,000.00", { timeout: 20_000 });
  await expect(page.getByRole("button", { name: "Award", exact: true })).toBeDisabled();
  await expect(page.locator(".prices-table")).not.toContainText("Reimbursables");
  await expect(page.locator(".prices-others")).toHaveCount(0);
  await quoted.getByText("Review total", {exact:true}).click();
  await quoted.getByRole("button", { name: "Confirm total for award" }).click();
  await expect(page.getByRole("button", { name: "Award", exact: true })).toBeEnabled();
  await page.getByRole("button", { name: /Show Interiors, joinery and finishes excerpts/ }).click();
  await expect(page.locator(".builder-section-detail")).toContainText("Kitchen allowance");
  await expect(page.locator(".builder-section-detail")).toContainText("Allowance; inclusion unresolved");
  const saved = await (await page.request.get(`${base}/prices`)).json();
  expect(saved.columns[0].cells["stage:lump_sum"].decided_by).toBe("user");
  expect(saved.columns[0].builder.ex_gst).toBe("100000.00");
  await page.getByRole("button", { name: "Award", exact: true }).click();
  await expect(page.getByRole("dialog")).not.toContainText("Kitchen allowance");
  await page.getByRole("dialog").getByRole("button", { name: "Cancel", exact: true }).click();
  await page.getByRole("button", { name: /Hide Interiors, joinery and finishes excerpts/ }).click();
  await quoted.getByText("Review total", {exact:true}).click();
  await page.getByLabel("Options for Example Builder").click();
  const sectionBox = await page.locator(".builder-section").last().boundingBox();
  const totalBox = await quoted.boundingBox();
  expect(sectionBox!.y).toBeLessThan(totalBox!.y);
  expect(totalBox!.y + totalBox!.height).toBeLessThan(900);
  await expect(page.locator(".prices-total")).toHaveCount(1);
  await page.screenshot({ path: "../.tools/builder-comparison-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(quoted.getByText("$100,000.00", { exact: true })).toBeVisible();
  await page.screenshot({ path: "../.tools/builder-comparison-mobile.png", fullPage: true });
});
