package rfp

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

const driverReportPath = "../../docs/evidence/2026-10-10-rfp-tranche1/driver-report.md"

// TestDriverReport writes, per scenario and discipline, which facts the rules
// read came from the profile, which the user set and which stay unknown, and
// which facts are set in more than one RFP of the same project (owner
// decision O9: evidence for which profile fields are worth adding).
// Regenerate with -update.
func TestDriverReport(t *testing.T) {
	cat := loadCatalog(t)
	sk, _ := cat.RFPSkeleton()
	var b strings.Builder
	b.WriteString("# Consultant RFP driver report\n\nGenerated by `go test ./internal/rfp -run DriverReport -update` from the draft answer keys in `data/eval/rfp/answer-keys/`. For each scenario and discipline: the facts its rules read, where each came from, and what stays unknown. A fact set by the user in more than one RFP of the same project is a candidate profile field (O9).\n\n")
	for _, s := range loadScenarios(t) {
		ids := make([]string, 0, len(s.Expect))
		for id := range s.Expect {
			ids = append(ids, id)
		}
		sort.Strings(ids)
		setIn := map[string][]string{}
		fmt.Fprintf(&b, "## %s\n\n%s\n\n| Discipline | From the profile or package | Set for this RFP | Unknown |\n|---|---|---|---|\n", s.Name, s.Description)
		for _, id := range ids {
			d, _ := cat.RFP(id)
			drivers := s.drivers(t, sk, d)
			settings := s.settings(t, id, drivers)
			r := Resolve(d, sk, drivers, settings)
			var profile, user, unknown []string
			used := usedDrivers(d, sk)
			keys := make([]string, 0, len(used))
			for k := range used {
				if k == "scale" || k == "stage" || k == "stage_included" || k == "element" {
					continue
				}
				keys = append(keys, k)
			}
			sort.Strings(keys)
			for _, k := range keys {
				label := factLabel(sk, k)
				if k == "class" {
					known := len(r.Parts) > 0
					for _, p := range r.Parts {
						known = known && len(p.Classes) > 0
					}
					if known {
						profile = append(profile, label)
					} else {
						unknown = append(unknown, label)
					}
					continue
				}
				f := r.Fact(k)
				switch {
				case f.Source == "user":
					user = append(user, label)
					setIn[label] = append(setIn[label], id)
				case f.State == Known:
					profile = append(profile, label)
				default:
					unknown = append(unknown, label)
				}
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", id, list(profile), list(user), list(unknown))
		}
		shared := []string{}
		for label, where := range setIn {
			if len(where) > 1 {
				shared = append(shared, fmt.Sprintf("%s (%s)", label, strings.Join(where, ", ")))
			}
		}
		sort.Strings(shared)
		if len(shared) > 0 {
			fmt.Fprintf(&b, "\nSet in more than one RFP: %s.\n", strings.Join(shared, "; "))
		}
		b.WriteString("\n")
	}
	got := b.String()
	if *update {
		if err := os.MkdirAll(filepath.Dir(driverReportPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(driverReportPath, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(driverReportPath)
	if err != nil || string(want) != got {
		t.Fatalf("driver report out of date; run with -update")
	}
}

func list(items []string) string {
	if len(items) == 0 {
		return "—"
	}
	return strings.Join(items, "; ")
}
